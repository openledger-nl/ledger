// ---- the vault on disk ------------------------------------------------------------------------------

/// A file's size and modification time: enough to notice that something else touched it.
type Fingerprint = (u64, u128);

pub struct Vault {
    root: PathBuf,
    /// The hash of the canonical text of every file this vault owns, as last written (or read).
    written: HashMap<String, u64>,
    /// What the managed folders looked like when we last wrote or read them.
    disk: BTreeMap<String, Fingerprint>,
}

impl Vault {
    /// Creates the folder if needed, along with a `.gitignore` that keeps local-only files out of GitHub.
    pub fn open(root: PathBuf) -> Result<Vault> {
        fs::create_dir_all(&root).map_err(|e| Error::io(&root, e))?;
        settings::ensure_gitignore(&root)?;
        Ok(Vault { root, written: HashMap::new(), disk: BTreeMap::new() })
    }

    pub fn root(&self) -> &Path {
        &self.root
    }

    /// Reads every file into a fresh in-memory database. Anything the files leave out or get wrong is repaired
    /// on the way in (a missing README is started, a link to a thread that does not exist is dropped) and
    /// written back out by the persist at the end.
    pub fn load(&mut self) -> Result<Connection> {
        let conn = db::open_in_memory()?;
        let listing = managed_listing(&self.root);
        import(&conn, &self.root, &listing)?;

        // A file that is already on disk is taken to match its canonical rendering, so that opening a vault
        // someone formatted by hand does not rewrite all of it.
        self.written.clear();
        for (path, content) in export(&conn)? {
            if listing.contains_key(&path) {
                self.written.insert(path, hash(&content));
            }
        }
        self.disk = listing;

        self.persist(&conn)?;
        Ok(conn)
    }

    /// Writes whatever differs between the database and the files, and deletes files whose thing is gone.
    /// Returns how many files were touched.
    pub fn persist(&mut self, conn: &Connection) -> Result<usize> {
        let canonical = export(conn)?;
        let mut touched = 0;

        for (path, content) in &canonical {
            let digest = hash(content);
            if self.written.get(path) == Some(&digest) {
                continue;
            }
            let file = self.root.join(path);
            write_atomic(&file, content).map_err(|e| Error::io(&file, e))?;
            self.written.insert(path.clone(), digest);
            if let Some(fp) = fingerprint(&file) {
                self.disk.insert(path.clone(), fp);
            }
            touched += 1;
        }

        let gone: Vec<String> = self.written.keys().filter(|p| !canonical.contains_key(*p)).cloned().collect();
        for path in gone {
            let file = self.root.join(&path);
            match fs::remove_file(&file) {
                Ok(()) => {}
                Err(e) if e.kind() == std::io::ErrorKind::NotFound => {}
                Err(e) => return Err(Error::io(&file, e)),
            }
            self.written.remove(&path);
            self.disk.remove(&path);
            prune_empty_dirs(&self.root, &file);
            touched += 1;
        }
        Ok(touched)
    }

    /// Whether files were added, removed or edited by something other than this vault since it last looked.
    pub fn changed_on_disk(&self) -> bool {
        managed_listing(&self.root) != self.disk
    }

    /// Forgets a project folder's leftovers after the project was deleted: attachments and non-markdown
    /// deliverables are not the database's to remove, so deleting a project removes its folder here.
    pub fn remove_project_dir(&mut self, project: &str) -> Result<()> {
        let dir = self.root.join("projects").join(project);
        if dir.is_dir() {
            fs::remove_dir_all(&dir).map_err(|e| Error::io(&dir, e))?;
        }
        self.disk.retain(|p, _| !p.starts_with(&format!("projects/{project}/")));
        self.written.retain(|p, _| !p.starts_with(&format!("projects/{project}/")));
        Ok(())
    }
}

fn hash(text: &str) -> u64 {
    let mut hasher = DefaultHasher::new();
    text.hash(&mut hasher);
    hasher.finish()
}

fn fingerprint(file: &Path) -> Option<Fingerprint> {
    let meta = fs::metadata(file).ok()?;
    let nanos = meta.modified().ok()?.duration_since(UNIX_EPOCH).ok()?.as_nanos();
    Some((meta.len(), nanos))
}

/// A file's modification time as an ISO timestamp, for files that don't say when they were created.
fn stamp_of(fp: Option<&Fingerprint>) -> String {
    fp.map_or_else(ids::now, |(_, nanos)| ids::format_millis((nanos / 1_000_000) as i64))
}

/// Whether the app looks at this path: markdown anywhere under `projects/`, `templates/` and `semesters/`, and any file at all
/// under a project's `deliverables/`.
fn managed(rel: &str) -> bool {
    let parts: Vec<&str> = rel.split('/').collect();
    (parts.len() >= 4 && parts[0] == "projects" && parts[2] == "deliverables") || rel.ends_with(".md")
}

/// Every managed file, with its fingerprint. Dotfiles (including the temporary files writes go through) are not
/// part of the vault, and neither is a project's `attachments/` folder.
fn managed_listing(root: &Path) -> BTreeMap<String, Fingerprint> {
    fn walk(root: &Path, rel: &str, out: &mut BTreeMap<String, Fingerprint>) {
        let Ok(entries) = fs::read_dir(root.join(rel)) else { return };
        for entry in entries.flatten() {
            let Some(name) = entry.file_name().to_str().map(str::to_string) else { continue };
            if name.starts_with('.') {
                continue;
            }
            let child = format!("{rel}/{name}");
            let Ok(kind) = entry.file_type() else { continue };
            if kind.is_dir() {
                let is_attachments = name == "attachments" && child.matches('/').count() == 2 && child.starts_with("projects/");
                if !is_attachments {
                    walk(root, &child, out);
                }
            } else if managed(&child)
                && let Some(fp) = fingerprint(&entry.path())
            {
                out.insert(child, fp);
            }
        }
    }

    let mut out = BTreeMap::new();
    for dir in ["projects", "templates", "semesters"] {
        walk(root, dir, &mut out);
    }
    out
}

/// Replaces the file in one step, so a crash mid-write never leaves half a note behind.
fn write_atomic(file: &Path, content: &str) -> std::io::Result<()> {
    if let Some(parent) = file.parent() {
        fs::create_dir_all(parent)?;
    }
    let name = file.file_name().and_then(|n| n.to_str()).unwrap_or("file");
    let temp = file.with_file_name(format!(".{name}.tmp"));
    fs::write(&temp, content)?;
    fs::rename(&temp, file)
}

/// After a delete, removes the folders it left empty, stopping at the vault root.
fn prune_empty_dirs(root: &Path, file: &Path) {
    let mut dir = file.parent();
    while let Some(current) = dir {
        if current == root || !current.starts_with(root) || fs::remove_dir(current).is_err() {
            break;
        }
        dir = current.parent();
    }
}

// ---- export: database → files -----------------------------------------------------------------------

/// The canonical text of every file the database owns, keyed by path relative to the vault root (always with `/`).
pub fn export(conn: &Connection) -> Result<BTreeMap<String, String>> {
    let mut files = BTreeMap::new();
    export_projects(conn, &mut files)?;
    export_threads(conn, &mut files)?;
    export_templates(conn, &mut files)?;
    export_semesters(conn, &mut files)?;
    export_stories_and_tasks(conn, &mut files)?;
    export_deliverables(conn, &mut files)?;
    export_version_records(conn, &mut files)?;
    Ok(files)
}

fn export_projects(conn: &Connection, files: &mut BTreeMap<String, String>) -> Result<()> {
    let mut columns: HashMap<String, Vec<Value>> = HashMap::new();
    for (project, id, name) in query_all(conn, "SELECT project_slug, id, name FROM project_columns ORDER BY project_slug, position", [], |r| {
        Ok((r.get::<_, String>(0)?, r.get::<_, String>(1)?, r.get::<_, String>(2)?))
    })? {
        let mut item = Mapping::new();
        frontmatter::set(&mut item, "id", id);
        frontmatter::set(&mut item, "name", name);
        columns.entry(project).or_default().push(Value::Mapping(item));
    }

    for (slug, name, description, readme, backlog, created_at, updated_at) in query_all(
        conn,
        "SELECT slug, name, description, readme, backlog_column_id, created_at, updated_at FROM projects",
        [],
        |r| Ok((r.get::<_, String>(0)?, r.get::<_, String>(1)?, r.get::<_, String>(2)?, r.get::<_, String>(3)?, r.get::<_, String>(4)?, r.get::<_, String>(5)?, r.get::<_, String>(6)?)),
    )? {
        let mut meta = Mapping::new();
        frontmatter::set(&mut meta, "name", name);
        frontmatter::set(&mut meta, "createdAt", created_at);
        frontmatter::set(&mut meta, "updatedAt", updated_at);
        frontmatter::set(&mut meta, "columns", Value::Sequence(columns.remove(&slug).unwrap_or_default()));
        frontmatter::set_opt(&mut meta, "backlogColumnId", Some(&backlog));
        files.insert(project_file(&slug), frontmatter::render(&meta, &description));
        files.insert(readme_file(&slug), readme);
    }
    Ok(())
}

fn export_threads(conn: &Connection, files: &mut BTreeMap<String, String>) -> Result<()> {
    let mut links: HashMap<(String, String), Vec<String>> = HashMap::new();
    for (project, a, b) in query_all(conn, "SELECT project_slug, a, b FROM thread_links ORDER BY project_slug, a, b", [], |r| {
        Ok((r.get::<_, String>(0)?, r.get::<_, String>(1)?, r.get::<_, String>(2)?))
    })? {
        links.entry((project.clone(), a.clone())).or_default().push(b.clone());
        links.entry((project, b)).or_default().push(a);
    }

    for (project, slug, title, description, created_at) in query_all(conn, "SELECT project_slug, slug, title, description, created_at FROM threads", [], |r| {
        Ok((r.get::<_, String>(0)?, r.get::<_, String>(1)?, r.get::<_, String>(2)?, r.get::<_, String>(3)?, r.get::<_, String>(4)?))
    })? {
        let mut linked = links.remove(&(project.clone(), slug.clone())).unwrap_or_default();
        linked.sort();
        let mut meta = Mapping::new();
        frontmatter::set(&mut meta, "title", title);
        frontmatter::set(&mut meta, "createdAt", created_at);
        frontmatter::set_list(&mut meta, "linkedThreadSlugs", &linked);
        files.insert(format!("{}/thread.md", thread_dir(&project, &slug)), frontmatter::render(&meta, &description));
    }

    type PostRow = (String, String, String, Option<String>, bool, bool, Option<String>, Option<String>, Option<String>, String, String, String);
    for (id, project, thread, parent, guiding, published, path, version, prompt, created_at, updated_at, body) in query_all::<PostRow, _>(
        conn,
        "SELECT id, project_slug, thread_slug, parent_id, guiding_question, version_published, deliverable_path,
                deliverable_version, prompt_id, created_at, updated_at, body FROM posts",
        [],
        |r| Ok((r.get(0)?, r.get(1)?, r.get(2)?, r.get(3)?, r.get(4)?, r.get(5)?, r.get(6)?, r.get(7)?, r.get(8)?, r.get(9)?, r.get(10)?, r.get(11)?)),
    )? {
        let mut meta = Mapping::new();
        frontmatter::set(&mut meta, "id", id.clone());
        frontmatter::set_opt(&mut meta, "parentId", parent.as_deref());
        frontmatter::set_flag(&mut meta, "guidingQuestion", guiding);
        frontmatter::set_flag(&mut meta, "versionPublished", published);
        frontmatter::set_opt(&mut meta, "deliverable", path.as_deref());
        frontmatter::set_opt(&mut meta, "deliverableVersion", version.as_deref());
        frontmatter::set_opt(&mut meta, "prompt", prompt.as_deref());
        frontmatter::set(&mut meta, "createdAt", created_at);
        frontmatter::set(&mut meta, "updatedAt", updated_at);
        files.insert(entity_file(&project, &thread, "posts", &id), frontmatter::render(&meta, &body));
    }

    let mut linked: HashMap<String, Vec<String>> = HashMap::new();
    for (prompt, path) in query_all(conn, "SELECT prompt_id, path FROM prompt_deliverables ORDER BY prompt_id, position", [], |r| {
        Ok((r.get::<_, String>(0)?, r.get::<_, String>(1)?))
    })? {
        linked.entry(prompt).or_default().push(path);
    }
    type PromptRow = (String, String, String, String, Option<String>, String, String, String);
    for (id, project, thread, title, template, created_at, updated_at, body) in query_all::<PromptRow, _>(
        conn,
        "SELECT id, project_slug, thread_slug, title, template_id, created_at, updated_at, body FROM prompts",
        [],
        |r| Ok((r.get(0)?, r.get(1)?, r.get(2)?, r.get(3)?, r.get(4)?, r.get(5)?, r.get(6)?, r.get(7)?)),
    )? {
        let mut meta = Mapping::new();
        frontmatter::set(&mut meta, "id", id.clone());
        frontmatter::set_opt(&mut meta, "title", Some(&title));
        frontmatter::set_opt(&mut meta, "template", template.as_deref());
        frontmatter::set_list(&mut meta, "deliverables", &linked.remove(&id).unwrap_or_default());
        frontmatter::set(&mut meta, "createdAt", created_at);
        frontmatter::set(&mut meta, "updatedAt", updated_at);
        files.insert(entity_file(&project, &thread, "prompts", &id), frontmatter::render(&meta, &body));
    }

    type FeedbackRow = (String, String, String, String, Option<String>, String, String, String, String);
    for (id, project, thread, path, version, status, created_at, updated_at, body) in query_all::<FeedbackRow, _>(
        conn,
        "SELECT id, project_slug, thread_slug, deliverable_path, deliverable_version, status, created_at, updated_at, body FROM feedback",
        [],
        |r| Ok((r.get(0)?, r.get(1)?, r.get(2)?, r.get(3)?, r.get(4)?, r.get(5)?, r.get(6)?, r.get(7)?, r.get(8)?)),
    )? {
        let mut meta = Mapping::new();
        frontmatter::set(&mut meta, "id", id.clone());
        frontmatter::set(&mut meta, "deliverable", path);
        frontmatter::set_opt(&mut meta, "version", version.as_deref());
        frontmatter::set(&mut meta, "status", status);
        frontmatter::set(&mut meta, "createdAt", created_at);
        frontmatter::set(&mut meta, "updatedAt", updated_at);
        files.insert(entity_file(&project, &thread, "feedback", &id), frontmatter::render(&meta, &body));
    }

    type UploadRow = (String, String, String, String, String, i64, String, String);
    for (id, project, thread, file, name, size, uploaded_at, description) in query_all::<UploadRow, _>(
        conn,
        "SELECT id, project_slug, thread_slug, file, name, size, uploaded_at, description FROM uploads",
        [],
        |r| Ok((r.get(0)?, r.get(1)?, r.get(2)?, r.get(3)?, r.get(4)?, r.get(5)?, r.get(6)?, r.get(7)?)),
    )? {
        let mut meta = Mapping::new();
        frontmatter::set(&mut meta, "id", id.clone());
        frontmatter::set(&mut meta, "uploadedAt", uploaded_at);
        frontmatter::set(&mut meta, "file", file);
        frontmatter::set(&mut meta, "name", name);
        frontmatter::set(&mut meta, "size", size);
        files.insert(entity_file(&project, &thread, "uploads", &id), frontmatter::render(&meta, &description));
    }

    let mut run_files: HashMap<String, Vec<String>> = HashMap::new();
    for (run, path) in query_all(conn, "SELECT run_id, path FROM claude_run_files ORDER BY run_id, position", [], |r| {
        Ok((r.get::<_, String>(0)?, r.get::<_, String>(1)?))
    })? {
        run_files.entry(run).or_default().push(path);
    }
    type RunRow = (String, String, String, String, String, String, String, String, String, i64, Option<i64>, String, String);
    for (id, project, thread, prompt, status, model, mode, started_at, finished_at, seconds, turns, body, provider) in query_all::<RunRow, _>(
        conn,
        "SELECT id, project_slug, thread_slug, prompt_id, status, model, permission_mode, started_at, finished_at, seconds, turns, body, provider
         FROM claude_runs",
        [],
        |r| Ok((r.get(0)?, r.get(1)?, r.get(2)?, r.get(3)?, r.get(4)?, r.get(5)?, r.get(6)?, r.get(7)?, r.get(8)?, r.get(9)?, r.get(10)?, r.get(11)?, r.get(12)?)),
    )? {
        let mut meta = Mapping::new();
        frontmatter::set(&mut meta, "id", id.clone());
        frontmatter::set(&mut meta, "prompt", prompt);
        frontmatter::set(&mut meta, "status", status);
        frontmatter::set_opt(&mut meta, "model", Some(&model));
        frontmatter::set_opt(&mut meta, "permissionMode", Some(&mode));
        frontmatter::set(&mut meta, "provider", provider);
        frontmatter::set(&mut meta, "startedAt", started_at);
        frontmatter::set(&mut meta, "finishedAt", finished_at);
        frontmatter::set(&mut meta, "seconds", seconds);
        if let Some(turns) = turns {
            frontmatter::set(&mut meta, "turns", turns);
        }
        frontmatter::set_list(&mut meta, "deliverables", &run_files.remove(&id).unwrap_or_default());
        files.insert(entity_file(&project, &thread, "runs", &id), frontmatter::render(&meta, &body));
    }
    Ok(())
}

fn export_templates(conn: &Connection, files: &mut BTreeMap<String, String>) -> Result<()> {
    let mut questions: HashMap<(String, String), Vec<String>> = HashMap::new();
    for (scope, id, question) in query_all(conn, "SELECT scope, template_id, question FROM template_questions ORDER BY scope, template_id, position", [], |r| {
        Ok((r.get::<_, String>(0)?, r.get::<_, String>(1)?, r.get::<_, String>(2)?))
    })? {
        questions.entry((scope, id)).or_default().push(question);
    }

    for (scope, id, name, trigger, body, created_at, updated_at) in query_all(
        conn,
        "SELECT scope, id, name, \"trigger\", body, created_at, updated_at FROM templates",
        [],
        |r| Ok((r.get::<_, String>(0)?, r.get::<_, String>(1)?, r.get::<_, String>(2)?, r.get::<_, String>(3)?, r.get::<_, String>(4)?, r.get::<_, String>(5)?, r.get::<_, String>(6)?)),
    )? {
        let mut meta = Mapping::new();
        frontmatter::set(&mut meta, "name", name);
        frontmatter::set_opt(&mut meta, "trigger", Some(&trigger));
        frontmatter::set_list(&mut meta, "questions", &questions.remove(&(scope.clone(), id.clone())).unwrap_or_default());
        frontmatter::set(&mut meta, "createdAt", created_at);
        frontmatter::set(&mut meta, "updatedAt", updated_at);
        files.insert(template_file(&scope, &id), frontmatter::render(&meta, &body));
    }
    Ok(())
}

fn export_semesters(conn: &Connection, files: &mut BTreeMap<String, String>) -> Result<()> {
    for semester in semesters::list(conn)? {
        let mut meta = Mapping::new();
        frontmatter::set(&mut meta, "name", semester.name);
        frontmatter::set(&mut meta, "start", semester.start);
        frontmatter::set(&mut meta, "end", semester.end);
        frontmatter::set(&mut meta, "sprintWeeks", semester.sprint_weeks);
        let sprints: Vec<Value> = semester
            .sprints
            .into_iter()
            .map(|s| {
                let mut item = Mapping::new();
                frontmatter::set(&mut item, "name", s.name);
                frontmatter::set(&mut item, "start", s.start);
                frontmatter::set(&mut item, "end", s.end);
                frontmatter::set_opt(&mut item, "goal", Some(&s.goal));
                Value::Mapping(item)
            })
            .collect();
        frontmatter::set(&mut meta, "sprints", Value::Sequence(sprints));
        let vacations: Vec<Value> = semester
            .vacations
            .into_iter()
            .map(|v| {
                let mut item = Mapping::new();
                frontmatter::set(&mut item, "name", v.name);
                frontmatter::set(&mut item, "start", v.start);
                frontmatter::set(&mut item, "end", v.end);
                Value::Mapping(item)
            })
            .collect();
        if !vacations.is_empty() {
            frontmatter::set(&mut meta, "vacations", Value::Sequence(vacations));
        }
        frontmatter::set(&mut meta, "createdAt", semester.created_at);
        frontmatter::set(&mut meta, "updatedAt", semester.updated_at);
        files.insert(semester_file(&semester.id), frontmatter::render(&meta, &semester.notes));
    }
    Ok(())
}

fn export_stories_and_tasks(conn: &Connection, files: &mut BTreeMap<String, String>) -> Result<()> {
    for project in query_all(conn, "SELECT slug FROM projects", [], |r| r.get::<_, String>(0))? {
        for story in crate::stories::list(conn, &project)? {
            let mut meta = Mapping::new();
            frontmatter::set(&mut meta, "id", story.id.clone());
            frontmatter::set(&mut meta, "summary", story.summary);
            frontmatter::set_opt(&mut meta, "role", Some(&story.role));
            frontmatter::set_opt(&mut meta, "want", Some(&story.want));
            frontmatter::set_opt(&mut meta, "reason", Some(&story.reason));
            let slugs: Vec<String> = story.threads.iter().map(|t| t.slug.clone()).collect();
            frontmatter::set_list(&mut meta, "threadSlugs", &slugs);
            if !story.criteria.is_empty() {
                let criteria = story
                    .criteria
                    .iter()
                    .map(|c| {
                        let mut item = Mapping::new();
                        frontmatter::set(&mut item, "text", c.text.clone());
                        frontmatter::set(&mut item, "done", c.done);
                        Value::Mapping(item)
                    })
                    .collect();
                frontmatter::set(&mut meta, "criteria", Value::Sequence(criteria));
            }
            frontmatter::set(&mut meta, "createdAt", story.created_at);
            frontmatter::set(&mut meta, "updatedAt", story.updated_at);
            frontmatter::set_opt(&mut meta, "trelloCard", story.trello_card.as_deref());
            frontmatter::set_opt(&mut meta, "trelloUnlinked", story.trello_unlinked.as_deref());
            files.insert(story_file(&project, &story.id), frontmatter::render(&meta, &story.notes));
        }

        for task in board::tasks(conn, &project)? {
            let mut meta = Mapping::new();
            frontmatter::set(&mut meta, "id", task.id.clone());
            frontmatter::set(&mut meta, "title", task.title);
            frontmatter::set(&mut meta, "columnId", task.column_id);
            frontmatter::set_opt(&mut meta, "story", task.story_id.as_deref());
            frontmatter::set_opt(&mut meta, "thread", task.thread_slug.as_deref());
            frontmatter::set(&mut meta, "createdAt", task.created_at);
            frontmatter::set(&mut meta, "updatedAt", task.updated_at);
            frontmatter::set_opt(&mut meta, "trelloCard", task.trello_card.as_deref());
            frontmatter::set_opt(&mut meta, "trelloUnlinked", task.trello_unlinked.as_deref());
            files.insert(task_file(&project, &task.id), frontmatter::render(&meta, &task.body));
        }
    }
    Ok(())
}

