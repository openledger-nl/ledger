//! The vault: a folder of markdown files with YAML frontmatter, laid out the way an Obsidian vault would be, so
//! it can be read, edited and searched with any other tool.
//!
//! ```text
//! templates/<id>.md                              a vault-wide template
//! semesters/<id>.md                              a semester and its sprints
//! projects/<project>/project.md                  a project: name, board columns
//! projects/<project>/README.md                   the project's reading guide
//! projects/<project>/threads/<thread>/thread.md  a thread
//!                                    /posts/<id>.md       its posts
//!                                    /prompts/<id>.md     its prompts (requests for deliverables)
//!                                    /feedback/<id>.md    its feedback (on a deliverable)
//!                                    /uploads/<id>.md     a manifest: when, where the file is, a description
//!                                    /runs/<id>.md        a run of a prompt with Claude Code: how it went, what it did
//! projects/<project>/versions/<id>.md            how a published version came to be: who made it, its thread, its AI-use label
//! projects/<project>/userstories/<id>.md         a user story
//! projects/<project>/tasks/<id>.md               a task on the board
//! projects/<project>/templates/<id>.md           the project's own templates
//! projects/<project>/deliverables/…              files generated by prompts, any type; "@v1.0" marks a published version
//! projects/<project>/attachments/…               files uploaded into threads, screenshots included
//! .ledger/                                       settings and secrets (see `settings`); never pushed
//! ```
//!
//! Files are the source of truth. [`Vault::load`] reads them into the in-memory database; after every change
//! [`Vault::persist`] writes the difference back. Persisting is a diff of the *whole* database's canonical file
//! rendering against what was last written, which makes it self-healing (a failed write is retried by the next
//! one) and keeps "what is on disk" a pure function of "what is in memory".
//!
//! Only text the database owns is rendered: the markdown entities above, the reading guides, and markdown
//! deliverables (kept verbatim). Every other file — other deliverables, attachments — is the filesystem's own;
//! the database knows deliverables by name and size, and the app copies or removes those files directly.

